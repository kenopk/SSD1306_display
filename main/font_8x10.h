// Возвращает указатель на 10 байт глифа по коду Unicode.
// Неизвестный символ рисуется как '?'.
static inline const uint8_t *font_get_glyph(uint32_t cp)
{
    if (cp >= FONT_FIRST_CHAR && cp <= FONT_LAST_CHAR) return font_8x10[cp - FONT_FIRST_CHAR];
    if (cp >= FONT_CYR_FIRST && cp <= FONT_CYR_LAST)   return font_8x10_cyr[cp - FONT_CYR_FIRST];
    if (cp == 0x0401) return font_8x10_cyr[FONT_CYR_COUNT - 2]; // 'Ё'
    if (cp == 0x0451) return font_8x10_cyr[FONT_CYR_COUNT - 1]; // 'ё'
    return font_8x10['?' - FONT_FIRST_CHAR];
}

// Читает один символ из строки UTF-8, возвращает его код Unicode
// и сдвигает указатель *s на следующий символ.
static inline uint32_t utf8_next(const char **s)
{
    const uint8_t *p = (const uint8_t *)*s;
    uint32_t cp;
    if (p[0] < 0x80) {                                  // 1 байт: ASCII
        cp = p[0];
        *s += 1;
    } else if ((p[0] & 0xE0) == 0xC0 && p[1]) {         // 2 байта: кириллица и др.
        cp = ((p[0] & 0x1F) << 6) | (p[1] & 0x3F);
        *s += 2;
    } else if ((p[0] & 0xF0) == 0xE0 && p[1] && p[2]) { // 3 байта
        cp = ((p[0] & 0x0F) << 12) | ((p[1] & 0x3F) << 6) | (p[2] & 0x3F);
        *s += 3;
    } else {                                            // битый байт: пропускаем
        cp = '?';
        *s += 1;
    }
    return cp;
}