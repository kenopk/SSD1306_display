#include "driver_i2c.h"

// ============================================================================
// 1. ИНИЦИАЛИЗАЦИЯ АППАРАТНОЙ ЧАСТИ (GPIO)
// ============================================================================
void i2c_gpio_init() {
    // Настраиваем пины SDA и SCL в режим "Открытый сток" (Open Drain).
    // ПОЧЕМУ ЭТО ВАЖНО: В этом режиме микроконтроллер может только притягивать 
    // линию к земле (логический 0). Он НЕ может выдавать 3.3В (логическую 1).
    // Это предотвращает короткое замыкание, если дисплей и ESP32 попытаются 
    // передать разные данные одновременно (мультимастерная архитектура I2C).
    gpio_set_direction(I2C_SDA_PIN, GPIO_MODE_INPUT_OUTPUT_OD); 
    gpio_set_direction(I2C_SCL_PIN, GPIO_MODE_INPUT_OUTPUT_OD);

    // Включаем внутренние подтягивающие (pull-up) резисторы чипа ESP32.
    // ПОЧЕМУ ЭТО ВАЖНО: Поскольку контроллер не может сам выдать "1", 
    // резистор пассивно "тянет" линию к напряжению питания (3.3В), 
    // создавая логическую "1" в состоянии покоя, когда никто не активен.
    gpio_pullup_en(I2C_SDA_PIN);    
    gpio_pullup_en(I2C_SCL_PIN);

    // Изначально "отпускаем" обе линии (записываем 1 в режим Open Drain).
    // Контроллер перестает притягивать линии к земле, и pull-up резисторы 
    // самостоятельно поднимают напряжение на шине до логической "1".
    // Согласно спецификации I2C, шина считается свободной только тогда, 
    // когда обе линии (SDA и SCL) находятся в состоянии HIGH.
    gpio_set_level(I2C_SDA_PIN, 1); 
    gpio_set_level(I2C_SCL_PIN, 1);
}

// ============================================================================
// 2. УСЛОВИЕ СТАРТ (START CONDITION)
// ============================================================================
void start_i2c(void) {
    // Шаг 1: Гарантируем, что шина свободна. Обе линии должны быть в HIGH (1).
    // Это обязательное условие перед началом любой передачи по I2C.
    gpio_set_level(I2C_SDA_PIN, 1);
    gpio_set_level(I2C_SCL_PIN, 1);
    esp_rom_delay_us(I2C_DELAY_US); // Ждем стабилизации сигнала (согласно tSSTART из даташита)

    // Шаг 2: Генерация условия START.
    // ПОЧЕМУ ЭТО РАБОТАЕТ: Согласно Figure 8-8 даташита, условием START является 
    // переход линии данных (SDA) из HIGH в LOW (1 -> 0) в тот момент, 
    // когда линия тактирования (SCL) удерживается в HIGH (1).
    // Это уникальный сигнал, который говорит всем устройствам на шине: 
    // "Внимание, начинается передача данных!".
    gpio_set_level(I2C_SDA_PIN, 0);
    esp_rom_delay_us(I2C_DELAY_US); // Выдерживаем время удержания START (tHSTART)

    // Шаг 3: Подготовка к передаче первого бита.
    // Согласно Figure 8-10 даташита, менять состояние линии SDA можно 
    // ТОЛЬКО тогда, когда линия SCL находится в состоянии LOW (0).
    // Поэтому мы немедленно опускаем SCL в 0, чтобы "разблокировать" линию SDA 
    // для безопасной записи первого бита адреса или данных.
    gpio_set_level(I2C_SCL_PIN, 0);
    esp_rom_delay_us(I2C_DELAY_US); // Выдерживаем половину тактового периода
}

// ============================================================================
// 3. УСЛОВИЕ СТОП (STOP CONDITION)
// ============================================================================
void stop_i2c(void) {
    // Шаг 1: Гарантируем, что линия данных (SDA) находится в LOW (0).
    // К этому моменту мы уже передали последний бит и опустили SCL в 0.
    // SDA должна быть равна 0 перед генерацией условия STOP.
    gpio_set_level(I2C_SDA_PIN, 0);
    esp_rom_delay_us(I2C_DELAY_US);

    // Шаг 2: Поднимаем линию тактирования (SCL) в HIGH (1).
    // Теперь обе линии находятся в разных состояниях: SCL = 1, SDA = 0.
    gpio_set_level(I2C_SCL_PIN, 1);
    esp_rom_delay_us(I2C_DELAY_US); // Выдерживаем время установки (tSSTOP)

    // Шаг 3: Генерация условия STOP.
    // ПОЧЕМУ ЭТО РАБОТАЕТ: Согласно Figure 8-8 даташита, условием STOP является 
    // переход линии данных (SDA) из LOW в HIGH (0 -> 1) в тот момент, 
    // когда линия тактирования (SCL) удерживается в HIGH (1).
    // Этот фронт сообщает дисплею: "Передача завершена, шина снова свободна".
    gpio_set_level(I2C_SDA_PIN, 1);
    esp_rom_delay_us(I2C_DELAY_US); // Даем шине время полностью стабилизироваться в HIGH
}

// ============================================================================
// 4. ПЕРЕДАЧА ОДНОГО БИТА (ATOMARНАЯ ОПЕРАЦИЯ)
// ============================================================================
void i2c_write_bit(bool bit) {
    // К моменту вызова этой функции SCL уже должен быть равен 0 (из start_i2c или предыдущего бита).
    
    // Шаг 1: Устанавливаем значение на линии SDA.
    // Если bit = 1, мы "отпускаем" линию, и pull-up резистор тянет её к 1.
    // Если bit = 0, мы активно притягиваем линию к земле.
    gpio_set_level(I2C_SDA_PIN, bit);
    esp_rom_delay_us(I2C_DELAY_US); // Время установки данных (tSD, Data Setup Time)

    // Шаг 2: Импульс тактирования (Clock High).
    // Поднимаем SCL в 1. ПОЧЕМУ ЭТО ВАЖНО: Именно в момент фронта (перехода 0 -> 1) 
    // или во время высокого уровня SCL ведомое устройство (дисплей SSD1306) 
    // "считывает" (семплирует) состояние линии SDA и запоминает переданный бит.
    gpio_set_level(I2C_SCL_PIN, 1); 
    esp_rom_delay_us(I2C_DELAY_US); // Время, необходимое дисплею на считывание (tHIGH)

    // Шаг 3: Завершение такта и подготовка к следующему биту.
    // Опускаем SCL обратно в 0. Теперь линия SDA снова "разблокирована" 
    // и мы можем безопасно менять её состояние для передачи следующего бита, 
    // не нарушая правил протокола I2C.
    gpio_set_level(I2C_SCL_PIN, 0); 
    esp_rom_delay_us(I2C_DELAY_US); // Время удержания данных после спада SCL (tHD)
}

// ============================================================================
// 5. ПЕРЕДАЧА ЦЕЛОГО БАЙТА (8 БИТ)
// ============================================================================
void i2c_write_byte(uint8_t byte) {
    // Протокол I2C требует передавать биты в порядке от Старшего (MSB, Bit 7) 
    // к Младшему (LSB, Bit 0). Поэтому цикл идет от 7 вниз до 0.
    for (int i = 0; i <= 7; i++) {
        
        // МАГИЯ БИТОВЫХ ОПЕРАЦИЙ:
        // 1. (byte & 0x80): Накладываем маску 10000000. Это обнуляет все биты, 
        //    кроме самого старшего (7-го). Если он был 1, результат будет 0x80 (не ноль).
        // 2. != 0: Преобразуем числовой результат в строгий логический тип bool (true или false).
        bool bit_to_send = (byte & 0x80) != 0; 
        
        // Отправляем извлеченный бит физически на шину через нашу функцию
        i2c_write_bit(bit_to_send);           
        
        // Сдвигаем все биты байта на 1 позицию влево.
        // ПОЧЕМУ ЭТО ЭФФЕКТИВНО: Бит №6 становится на место бита №7 (старшего). 
        // На следующей итерации цикла мы снова применим маску 0x80 и легко 
        // прочитаем уже этот, новый старший бит.
        byte <<= 1;                   
    }

    // ВАЖНОЕ ПРИМЕЧАНИЕ НА БУДУЩЕЕ:
    // После отправки 8 битов байта, по спецификации I2C (Figure 8-9), 
    // ведомое устройство (дисплей) должно отправить бит подтверждения (ACK).
    // Для этого дисплей притянет SDA к 0 на 9-м такте SCL. 
    // В текущей реализации мы игнорируем чтение ACK для простоты, 
    // но физически на 9-м такте дисплей попытается это сделать.
}

bool i2c_read_ack(void) {
    // 1. Отпускаем линию SDA (режим Open Drain + pull-up тянет к 1)
    gpio_set_level(I2C_SDA_PIN, 1); 
    esp_rom_delay_us(I2C_DELAY_US);  

    // 2. Генерируем 9-й тактовый импульс (поднимаем SCL)
    gpio_set_level(I2C_SCL_PIN, 1);
    esp_rom_delay_us(I2C_DELAY_US);

    // 3. Читаем ответ дисплея
    bool ack_received = (gpio_get_level(I2C_SDA_PIN) == 0);

    // 4. ЗАВЕРШАЕМ ТАКТ: опускаем SCL обратно в 0, чтобы подготовить шину к следующему действию
    gpio_set_level(I2C_SCL_PIN, 0);
    esp_rom_delay_us(I2C_DELAY_US);

    return ack_received; // true (1) если ACK, false (0) если NACK
}